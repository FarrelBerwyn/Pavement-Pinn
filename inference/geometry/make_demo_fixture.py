"""Build the DATA CONTOH workspace fixture (src/data/fixtures/workspace-demo.json).

Every number in it is produced by running this repository's code:
- Pothole geometry: geometry.pipeline.run_pothole on a SYNTHETIC depression whose outline is traced
  from the detection photo F01 (geometry.footprint), so the 3D shape follows the detected damage.
  Depth inside that outline is synthetic (no depth is measured from one photo).
- Structural run: app.mlet (PyMastic) critical strains and field grid with ASSUMED layers.
Nothing is copied from the mockups. Run from inference/:
    .venv/bin/python -m geometry.make_demo_fixture
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from app.mlet import METHOD, allowable_reps, life_index_years, mlet_field_grid, mlet_strains
from geometry.pipeline import requantify
from geometry import GeometryConfig
from geometry.pipeline import run_pothole
from geometry.footprint import footprint_depression, load_gray, segment_footprint
from geometry.synthetic import v_groove
from geometry.pipeline import crack_from_grid

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src" / "data" / "fixtures" / "workspace-demo.json"
F01 = "dataset-reference/rdd2022/D40/Czech_000108.jpg"
VIEW_PX = 600  # CameraTab draws masks/boxes in a 600×600 frame


def detection_footprint() -> tuple[dict, list[tuple[float, float]]]:
    """Trace F01's pothole inside its RDD2022 box; return the segmentation and the mask polygon in viewer px."""
    reg = json.loads((ROOT / "src" / "data" / "reference" / "datasetImageRegistry.json").read_text())
    a = next(x for x in reg["assets"] if x["storagePath"] == F01)
    k = a["crop"]["outputSize"] / a["crop"]["size"]
    b = a["annotationBox"]
    box = ((b["xmin"] - a["crop"]["x"]) * k, (b["ymin"] - a["crop"]["y"]) * k, (b["xmax"] - a["crop"]["x"]) * k, (b["ymax"] - a["crop"]["y"]) * k)
    seg = segment_footprint(load_gray(ROOT / "public" / F01), box)
    v = VIEW_PX / a["crop"]["outputSize"]
    return seg, [(round(x * v, 1), round(y * v, 1)) for x, y in seg["polygon_px"]]


def main() -> None:
    seg, mask_view = detection_footprint()
    # ASSUMED scale: footprint long side ≈ 520 mm (no scale marker in F01).
    poly = np.asarray(seg["polygon_px"])
    mm_per_px = 520.0 / float((poly.max(0) - poly.min(0)).max())
    s = footprint_depression(seg["polygon_px"], seg["darkness"], seg["origin_px"], mm_per_px,
                             size_mm=800, step_mm=4, depth_mm=38, tilt=(0.01, 0.0), noise_mm=0.5, seed=3)
    geo = run_pothole(s["points"], mm_per_unit=1.0, scale_uncertainty_mm=0.8, cfg=GeometryConfig(grid_m=100))

    layers = {"h": [100, 250, 200], "E": [3000, 300, 150], "nu": [0.35, 0.35, 0.35]}
    e_sub, nu_sub = 60.0, 0.45  # E = 10 x CBR 6 (ASSUMED)
    args = (8.16, layers["h"], layers["E"] + [e_sub], layers["nu"] + [nu_sub])
    strains = mlet_strains(*args, dual_spacing_mm=330)
    field = mlet_field_grid(*args, dual_spacing_mm=330, x_mm=[float(v) for v in np.arange(-800, 801, 50)],
                            z_mm=[float(v) for v in np.arange(10, 801, 25)])
    nf, nd = allowable_reps(strains["et_ue"], strains["ev_ue"], layers["E"][0], "AI")

    completed = completed_scenario(s, geo)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({
        "_comment": "DATA CONTOH. Generated by inference/geometry/make_demo_fixture.py; synthetic surface + MLET with ASSUMED inputs.",
        "geometry": {"objectId": "POTHOLE-024", "synthetic": True, "footprint": {"frameId": "F01", "mask_px": mask_view,
                     "mm_per_px": round(mm_per_px, 4), "method": "dark-region trace inside the RDD2022 box; depth synthetic"}, "unit": geo["unit"], "step": geo["step"],
                     "boundary_depth": geo["boundary_depth"], "plane_rms": geo["plane_rms"], "coverage_pct": geo["coverage_pct"],
                     "grid_empty_pct": geo["grid_empty_pct"], "tilt_deg": geo["tilt_deg"], "metrics": geo["metrics"],
                     "contour": geo["contour"], "depth_grid": geo["depth_grid"]},
        "structural": {"method": METHOD, "layers": layers, "subgrade": {"E_mpa": e_sub, "nu": nu_sub}, "axle_t": 8.16,
                       "dual_spacing_mm": 330, "strains": strains, "allowable": {"nf": float(nf), "nd": float(nd)}, "field": field},
        "completed": completed,
    }, separators=(",", ":")))
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KiB)")


def completed_scenario(s: dict, geo: dict) -> dict:
    """ROAD-2026-002: the same synthetic pothole carried through the whole flow.
    - F.E contour: the outline traced from the detection photo (same shape as the surface),
      rerun with a ring-refitted plane (requantify, the same call the server makes).
    - Field points: "caliper" reference = the noise-free synthetic depth at the point,
      rounded to 0.5 mm like a caliper reading; system value = stored grid cell (as the server reads it).
    - Layers: AC 120 mm from a SIMULATED core, subgrade E from a SIMULATED DCP (CBR 5 -> 50 MPa);
      base/subbase stay ASSUMED. Traffic ESAL/day ASSUMED lognormal; life index from MLET + Miner.
    Everything is DATA CONTOH."""
    grid = geo["depth_grid"]
    step = geo["step"]
    d = np.array([[np.nan if v is None else v for v in row] for row in grid], dtype=float)
    r0, c0 = np.unravel_index(np.nanargmax(d), d.shape)
    cx, cy = (c0 + 0.5) * step, (r0 + 0.5) * step
    truth = s["depth"]
    # The pipeline grid has its own origin/step (plane frame); align the synthetic surface to it by depth centroid.
    def centroid(a: np.ndarray, st: float) -> np.ndarray:
        w = np.where(np.isfinite(a) & (a > 1.0), a, 0.0)
        r, c = np.indices(a.shape)
        return np.array([((c + 0.5) * w).sum(), ((r + 0.5) * w).sum()]) * st / w.sum()
    off = centroid(d, step) - centroid(truth, s["step"])
    contour = [(round(x + off[0], 1), round(y + off[1], 1)) for x, y in s["contour_mm"]]
    fixed = requantify(grid, step, contour, metric=True, plane_rms=geo["plane_rms"], scale_uncertainty_mm=0.8, refit_plane=True)

    points = []
    for i, (dx, dy) in enumerate([(0, 0), (40, 0), (0, -70), (-100, 30), (60, 110)]):
        x, y = cx + dx, cy + dy
        analytic = truth[int((y - off[1]) // s["step"]), int((x - off[0]) // s["step"])]
        cell = d[int(y // step), int(x // step)]
        points.append({"x_mm": round(float(x), 1), "y_mm": round(float(y), 1), "reference_mm": round(float(analytic) * 2) / 2,
                       "system_mm": None if not np.isfinite(cell) else round(float(cell), 1), "label": f"T{i + 1}"})

    layers = {"h": [120, 250, 200], "E": [3000, 300, 150], "nu": [0.35, 0.35, 0.35]}
    e_sub, nu_sub = 50.0, 0.45
    args = (8.16, layers["h"], layers["E"] + [e_sub], layers["nu"] + [nu_sub])
    strains = mlet_strains(*args, dual_spacing_mm=330)
    field = mlet_field_grid(*args, dual_spacing_mm=330, x_mm=[float(v) for v in np.arange(-800, 801, 50)],
                            z_mm=[float(v) for v in np.arange(10, 801, 25)])
    nf, nd = allowable_reps(strains["et_ue"], strains["ev_ue"], layers["E"][0], "AI")
    n_allow = float(min(nf, nd))
    rng = np.random.default_rng(11)
    esal_day = rng.lognormal(mean=np.log(600), sigma=0.35, size=200)  # ASSUMED traffic spread
    lives = np.array([life_index_years(n_allow, e * 365 * 0.5, 0.04, 0.0) for e in esal_day])
    hist, edges = np.histogram(lives, bins=24)
    # CRACK-032: SYNTHETIC longitudinal V-groove (analytic width 10 mm, depth 6 mm, length 400 mm),
    # quantified with the same crack_from_grid call the server makes.
    g = v_groove(length_mm=400, width_mm=10, depth_mm=6, step_mm=2.0, span_mm=80)
    crack = crack_from_grid(g["depth_grid"].tolist(), g["step"], metric=True, plane_rms=0.0)
    crack_block = {"step": g["step"], "depth_grid": [[round(float(v), 3) for v in row] for row in g["depth_grid"]],
                   "analytic": {"width_mm": 10.0, "depth_mm": 6.0, "length_mm": 400.0},
                   "metrics": crack["metrics"], "crack_map": crack["crack_map"], "skeleton": crack["skeleton"],
                   "coverage_pct": crack["coverage_pct"], "is_crack": crack["is_crack"]}

    return {
        "crack": crack_block,
        "contour": contour, "metrics": fixed["metrics"], "coverage_pct": fixed["coverage_pct"], "plane_rms": fixed["plane_rms"],
        "points": points,
        "structural": {"method": METHOD, "layers": layers, "subgrade": {"E_mpa": e_sub, "nu": nu_sub}, "strains": strains,
                       "allowable": {"nf": float(nf), "nd": float(nd), "governing": "fatigue" if nf <= nd else "rutting"}, "field": field,
                       "traffic": {"esal_day_median": 600, "lognormal_sigma": 0.35, "growth": 0.04, "direction_factor": 0.5, "samples": 200},
                       "life": {"p10": float(np.percentile(lives, 10)), "p50": float(np.percentile(lives, 50)), "p90": float(np.percentile(lives, 90)),
                                "histogram": [int(v) for v in hist], "bin_edges": [float(v) for v in edges]}},
    }


if __name__ == "__main__":
    main()
